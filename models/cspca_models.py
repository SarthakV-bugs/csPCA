    img_tensor, label_tensor, _ = dataset[sample_idx] # Added is_positive to unpacking
    input_tensor = img_tensor.unsqueeze(0).to(device)

    with torch.no_grad():
        output_tensor = model(input_tensor)

    img_cpu = img_tensor.squeeze(0).cpu().numpy()
    label_cpu = label_tensor.cpu().numpy()
    # Apply sigmoid to outputs here for thresholding
    pred_cpu = (torch.sigmoid(output_tensor) > 0.5).squeeze().cpu().numpy()


    fig, axes = plt.subplots(1, 3, figsize=(15, 5))

    axes[0].imshow(img_cpu, cmap='bone')
