    axes[0].axis('off')

    axes[1].imshow(label_cpu, cmap='gray')
    axes[1].set_title('Ground Truth')
    axes[1].axis('off')

    axes[2].imshow(pred_cpu, cmap='gray')
    axes[2].set_title('Prediction (Threshold 0.5)')
    axes[2].axis('off')

    plt.tight_layout()
